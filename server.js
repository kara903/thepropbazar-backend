// /api/chat Endpoint (Context-aware retrieval + Groq AI / Gemini AI)
app.post('/api/chat', async (req, res) => {
    const { message, history = [], currentProject = "", currentBhk = "" } = req.body;

    if (!message || !message.trim()) {
        return res.status(400).json({ error: "Message is required." });
    }

    const groqApiKey = process.env.GROQ_API_KEY?.trim();
    const requestedModel = process.env.GROQ_MODEL?.trim() || 'openai/gpt-oss-20b';

    try {
        const cleanMessage = message.trim();
        const recentHistory = Array.isArray(history) ? history.filter(t => t && t.text && t.role).slice(-8) : [];

        // Build a retrieval query that includes context for references or short follow-ups
        const referenceWords = /\b(isme|usme|iska|uska|ye|wo|vo|pichla|previous|that|this|it)\b/i.test(cleanMessage)
            || /(इसमें|उसमें|इसका|उसका|ये|वो|पिछला|पहले वाला|उस project)/i.test(cleanMessage);
        const isShortQuery = cleanMessage.split(/\s+/).length <= 4;

        let retrievalParts = [];
        if (currentProject) retrievalParts.push(`Project: ${currentProject}`);
        if (currentBhk) retrievalParts.push(`BHK: ${currentBhk}`);

        if (referenceWords || isShortQuery) {
            for (const turn of recentHistory.slice(-4)) {
                retrievalParts.push(`${turn.role}: ${turn.text}`);
            }
        } else {
            const previousUser = [...recentHistory].reverse().find(t => t.role === 'user' && t.text.trim() !== cleanMessage);
            if (previousUser && /(compare|difference|isme|usme|iska|uska|ye|wo|this|that|it|bhk|lakh|लाख|बजट)/i.test(cleanMessage)) {
                retrievalParts.push(`Previous customer context: ${previousUser.text}`);
            }
        }
        retrievalParts.push(`Current customer request: ${cleanMessage}`);

        const retrievalQuery = retrievalParts.join('\n');

        const vectorResults = await searchVectorDatabase(retrievalQuery, {
            currentProject,
            currentBhk,
            maxResults: 4
        });

        let dynamicKnowledge = "";
        if (vectorResults && vectorResults.length) {
            dynamicKnowledge = "RELEVANT PROPERTY KNOWLEDGE:\n" + vectorResults.slice(0, 8).map((doc, i) =>
                `${i + 1}. [${doc.project_name || 'Property'} | ${doc.category || 'General'}]\n${doc.content}`
            ).join('\n\n');
        } else if (propertyDataSummary) {
            dynamicKnowledge = `PROPERTY KNOWLEDGE FALLBACK:\n${propertyDataSummary}`;
        } else {
            dynamicKnowledge = "No property information was retrieved.";
        }

        function cleanText(txt) {
            if (!txt) return "";
            let s = String(txt).replace(/<think>[\s\S]*?<\/think>/gi, '').trim();
            s = s.replace(/\*\*/g, '').replace(/[\#\_\*]/g, '').trim();
            s = s.replace(/(\d+(?:\.\d+)?)\s*[\-–—‑]\s*(\d+(?:\.\d+)?)/g, '$1 से $2');
            s = s.replace(/sq\.?\s*ft\.?/gi, 'स्क्वायर फीट');
            s = s.replace(/sqft/gi, 'स्क्वायर फीट');
            s = s.replace(/sq\s*feet/gi, 'स्क्वायर फीट');
            s = s.replace(/\bSIDCUL\b/gi, 'सिडकुल');
            s = s.replace(/\bBHEL\b/gi, 'भेल');
            s = s.replace(/\bNH[- ]?58\b/gi, 'नेशनल हाईवे 58');
            s = s.replace(/\bRERA\b/gi, 'रेरा');
            // Strip repetitive leading greetings from mid-conversation replies
            s = s.replace(/^(?:नमस्ते|नमस्कार|हेलो|हाय|हैलो)\s*(?:जी)?[\s,।!\-–—]*\s*/i, '');
            // Strip trailing generic robotic follow-up questions from AI reply
            s = s.replace(/(?:[।!\n]|^)\s*(?:क्या आप (?:और|कोई|इस|इनमें से|इसे)[^।!\n]*\?|क्या मैं आपकी और[^।!\n]*\?|बताइए[^।!\n]*[\?।!])\s*$/i, '');
            return s.trim();
        }

        const primaryProvider = (process.env.PRIMARY_AI_PROVIDER || 'gemini').toLowerCase();
        const geminiApiKey = (process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY)?.trim();
        const geminiModel = process.env.GEMINI_MODEL?.trim() || 'gemini-3.5-flash';
        let reply = "";
        let usedModel = "";
        const tStartLLM = Date.now();

        async function runGroq() {
            if (!groqApiKey) return null;
            const messages = [
                {
                    role: 'system',
                    content: `${BASE_VOICE_INSTRUCTIONS}\n\nCURRENT RETRIEVED KNOWLEDGE:\n${dynamicKnowledge}`
                }
            ];

            if (currentProject || currentBhk) {
                messages.push({
                    role: 'system',
                    content: `CURRENT WEBSITE CONTEXT: ${currentProject || 'all projects'}${currentBhk ? ` | BHK: ${currentBhk}` : ''}`
                });
            }

            for (const turn of recentHistory) {
                if (turn.text.trim() === cleanMessage) continue;
                messages.push({
                    role: turn.role === 'user' ? 'user' : 'assistant',
                    content: turn.text
                });
            }

            messages.push({ role: 'user', content: cleanMessage });

            const modelsPool = [
                requestedModel,
                'qwen/qwen3.6-27b',
                'openai/gpt-oss-20b',
                'allam-2-7b',
                'openai/gpt-oss-120b'
            ].filter((v, i, a) => a.indexOf(v) === i);

            for (const currentModel of modelsPool) {
                try {
                    let response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
                        method: 'POST',
                        headers: {
                            'Authorization': `Bearer ${groqApiKey}`,
                            'Content-Type': 'application/json'
                        },
                        body: JSON.stringify({
                            model: currentModel,
                            messages,
                            temperature: 0.25,
                            max_tokens: 600
                        })
                    });
                    let data = await response.json();
                    if (data?.error) {
                        console.warn(`Groq [${currentModel}] rate limit or error, switching model...`);
                        continue;
                    }
                    const text = cleanText(data?.choices?.[0]?.message?.content || data?.choices?.[0]?.message?.reasoning);
                    if (text && text.length > 2) {
                        usedModel = `Groq ${currentModel}`;
                        return text;
                    }
                } catch (err) {
                    console.warn(`Groq [${currentModel}] error: ${err.message}`);
                }
            }
            return null;
        }

        async function runGemini() {
            if (!geminiApiKey) return null;
            const systemPromptText = `${BASE_VOICE_INSTRUCTIONS}\n\nCURRENT RETRIEVED KNOWLEDGE:\n${dynamicKnowledge}` +
                (currentProject || currentBhk ? `\n\nCURRENT WEBSITE CONTEXT: ${currentProject || 'all projects'}${currentBhk ? ` | BHK: ${currentBhk}` : ''}` : '');

            const contents = [];
            for (const turn of recentHistory) {
                if (turn.text.trim() === cleanMessage) continue;
                contents.push({
                    role: turn.role === 'user' ? 'user' : 'model',
                    parts: [{ text: turn.text }]
                });
            }
            contents.push({ role: 'user', parts: [{ text: cleanMessage }] });

            const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/${geminiModel}:generateContent`;
            const geminiRes = await fetch(geminiUrl, {
                method: 'POST',
                headers: {
                    'x-goog-api-key': geminiApiKey,
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify({
                    contents,
                    systemInstruction: { parts: [{ text: systemPromptText }] },
                    generationConfig: {
                        temperature: 0.2,
                        maxOutputTokens: 600
                    }
                })
            });
            const geminiData = await geminiRes.json();
            const rawReply = geminiData?.candidates?.[0]?.content?.parts?.[0]?.text;
            return rawReply ? cleanText(rawReply) : null;
        }

        // Execute primary provider with automatic fallback
        if (primaryProvider === 'groq') {
            try {
                reply = await runGroq();
                if (reply) usedModel = `Groq ${requestedModel}`;
            } catch (e) {
                console.warn("Groq failed, trying Gemini:", e.message);
            }
            if (!reply) {
                try {
                    reply = await runGemini();
                    if (reply) usedModel = `Google ${geminiModel}`;
                } catch (e) {
                    console.warn("Gemini fallback also failed:", e.message);
                }
            }
        } else {
            try {
                reply = await runGemini();
                if (reply) usedModel = `Google ${geminiModel}`;
            } catch (e) {
                console.warn("Gemini failed, trying Groq:", e.message);
            }
            if (!reply) {
                try {
                    reply = await runGroq();
                    if (reply) usedModel = `Groq ${requestedModel}`;
                } catch (e) {
                    console.warn("Groq fallback failed:", e.message);
                }
            }
        }

        const tLLM = Date.now() - tStartLLM;

        let audioContent = null;
        const tStartTTS = Date.now();
        try {
            const { synthesizeSpeech } = require('./scripts/google-tts');
            if (reply) audioContent = await synthesizeSpeech(reply);
        } catch (ttsErr) {
            console.warn("Google TTS notice:", ttsErr.message);
        }
        const tTTS = Date.now() - tStartTTS;

        console.log(`⚡ [Timing] LLM (${usedModel}): ${tLLM}ms | TTS: ${tTTS}ms | Total Voice Pipeline: ${tLLM + tTTS}ms`);

        if (reply) {
            return res.json({ reply, model: usedModel || requestedModel, audioContent });
        }

        return res.json({ reply: "इसकी exact जानकारी अभी उपलब्ध नहीं है." });
    } catch (err) {
        console.error("Chat API error:", err);
        return res.json({ reply: "इसकी exact जानकारी अभी उपलब्ध नहीं है. थोड़ी देर बाद फिर try करें." });
    }
});

